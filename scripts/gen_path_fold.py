#!/usr/bin/env python3
"""Writes core/src/util/path_fold_table.h: the table mc_path_key() folds names with.

For each code point: canonical decomposition (NFD), full case folding, NFD again, combining
marks (category Mn) dropped. So every spelling of a name, NFC or NFD and in any case, comes
out the same. Hangul syllables aren't listed: pathkey.c decomposes them by arithmetic. Run
it again only to take in a newer Unicode:

    python scripts/gen_path_fold.py core/src/util/path_fold_table.h
"""
import sys
import unicodedata as ud


def fold(c):
    s = ud.normalize("NFD", ud.normalize("NFD", c).casefold())
    return "".join(x for x in s if ud.category(x) != "Mn")


rows, marks = [], []
for cp in range(0x80, 0x110000):
    if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
        continue
    c = chr(cp)
    if ud.category(c) == "Mn":
        if marks and marks[-1][1] == cp - 1:
            marks[-1][1] = cp
        else:
            marks.append([cp, cp])
        continue
    f = fold(c)
    if f != c:
        assert 1 <= len(f) <= 3, hex(cp)
        rows.append((cp, [ord(x) for x in f] + [0] * (3 - len(f))))

with open(sys.argv[1], "w", newline="\n") as out:
    out.write("/* Generated by scripts/gen_path_fold.py from Unicode %s. Don't edit. */\n" % ud.unidata_version)
    out.write("static const struct {\n  uint32_t cp, to[3];\n} k_path_fold[] = {\n")
    for cp, to in rows:
        out.write("  {0x%X, {0x%X, 0x%X, 0x%X}},\n" % (cp, to[0], to[1], to[2]))
    out.write("};\n\nstatic const struct {\n  uint32_t first, last;\n} k_path_marks[] = {\n")
    for a, b in marks:
        out.write("  {0x%X, 0x%X},\n" % (a, b))
    out.write("};\n")
